def _basename(photo):
    url = photo.get('source', '')
    return Path(urlsplit(url).path).name.casefold() or Path(photo.get('file', '')).name.casefold()


def _photo_index(photos):
    result = {}
    for p in photos:
        result.setdefault(_basename(p), []).append(p)
    return result


def _inline_fragment(contents, prefix='f1dmg/'):
    """Reuse the original, locally sanitized HTML fragment on the landing page.

    Fragment links are relative to site/f1dmg/page-20.html. The landing page
    is one level above; only generated local photo/document links are prefixed.
    """
    return re.sub(r'(?P<attr>\b(?:src|href)=["\'])(?P<path>(?:photos|documents)/[^"\']+)(?P<end>["\'])',
                  lambda m: m.group('attr') + prefix + m.group('path') + m.group('end'),
                  contents)


def _media_card(p, root_prefix, photo_type='Photo'):
    rel = p.get('file', '').removeprefix('photos/')
    if not rel or '/' in rel or '\\' in rel:
        return ''
    src = root_prefix + 'photos/' + esc(rel)
    name = Path(urlsplit(p.get('source', '')).path).name or rel
    alt = p.get('title') or name
    return (f'<figure class="f1dmg-story-photo"><a href="{src}" target="_blank" rel="noopener" title="Agrandir {esc(name)}">'
            f'<img src="{src}" alt="{esc(alt)}" loading="lazy" decoding="async"></a>'
            f'<figcaption><strong>{esc(name)}</strong> · Photo publiée sur le site de F1DMG'
            f'<span class="f1dmg-origin"> <a href="{esc(p.get("source", "#"))}" rel="noopener noreferrer" target="_blank">Adresse historique</a></span>'
            '</figcaption></figure>')


def _story_html(story, indexed, documents):
    matched = []
    seen = set()
    for name in story['images']:
        for p in indexed.get(name.casefold(), []):
            if p.get('file') not in seen:
                matched.append(p)
                seen.add(p.get('file'))
    illustrations = ''.join(_media_card(p, 'f1dmg/') for p in matched)
    if not illustrations and story['images']:
        illustrations = '<p class="f1dmg-image-pending">Photographies conservées dans l’archive F1DMG : ' + ', '.join('<code>'+esc(n)+'</code>' for n in story['images']) + '. Importer la sauvegarde pour les afficher ici.</p>'
    links = []
    lookup = {Path(urlsplit(doc.get('source','')).path).name.casefold():doc for doc in documents}
    for name in story['docs']:
        doc = lookup.get(name.casefold())
        if doc:
            safe = Path(doc['file']).name
            links.append(f'<a href="f1dmg/documents/{esc(safe)}" download>{esc(name)}</a>')
    para = ''.join('<p>'+esc(t)+'</p>' for t in story['paragraphs'])
    docs_html = ('<p class="f1dmg-story-docs"><strong>Documents associés :</strong> '+ ' · '.join(links) + '</p>') if links else ''
    return (f'<section class="f1dmg-story" id="{esc(story["id"])}">'
            f'<div class="f1dmg-story-heading"><span class="f1dmg-label">{esc(story["kind"])}</span>'
            f'<h2>{esc(story["title"])}</h2></div>'
            f'<div class="f1dmg-story-layout"><div class="f1dmg-story-copy">{para}{docs_html}'
            f'<p class="f1dmg-bench"><strong>Pour OpenD578 :</strong> {esc(story["bench"])}</p></div>'
            f'{("<div class=\"f1dmg-story-media\">"+illustrations+"</div>") if illustrations else ""}</div></section>')


